import type { ConfidenceReason } from "@/lib/confidence";
import { FIELD_LABELS, FIELD_NAMES } from "@/lib/invoice";
import { summarize, type DocOutcome, type DocScore, type Metrics } from "./score";

/**
 * An eval report: the run's settings, every metric, and per invoice what was
 * wrong. Written as JSON (the record numbers are cited from) and as a short
 * markdown summary next to it.
 */

export type RunInfo = {
  run: string;
  mode: "live" | "replay";
  /** For a replay: the run whose saved answers were re-scored. */
  replayOf?: string;
  ranAt: string;
  promptVersion: string;
  model: string;
  effort: string;
  split: string;
  /** False when the run stopped early (spend cap); its metrics cover only the invoices it finished. */
  complete: boolean;
};

export type Report = RunInfo & { metrics: Metrics; documents: ReturnType<typeof documentDetail>[] };

function documentDetail(score: DocScore, outcome: DocOutcome) {
  return {
    id: score.id,
    kind: score.kind,
    route: score.route,
    fullyCorrect: score.fullyCorrect,
    escapedFields: score.escapedFields,
    escaped: score.escaped,
    error: outcome.error,
    wrong: FIELD_NAMES.filter((name) => !score.fields[name].correct).map((name) => ({
      field: name,
      got: score.fields[name].got,
      want: score.fields[name].want,
      high: score.fields[name].high,
      reasons: (outcome.confidence?.[name].reasons ?? []) as ConfidenceReason[],
    })),
    lines: { matched: score.lines.matched, extracted: score.lines.extracted, truth: score.lines.truth, missed: score.lines.missed, extra: score.lines.extra },
    costUsd: Number(score.costUsd.toFixed(6)),
    seconds: Number((score.ms / 1000).toFixed(2)),
    attempts: outcome.attempts.length,
    fallbackUsed: outcome.attempts.some((a) => a.fallbackUsed),
  };
}

export function buildReport(info: RunInfo, scored: { score: DocScore; outcome: DocOutcome }[]): Report {
  return { ...info, metrics: summarize(scored.map((s) => s.score)), documents: scored.map(({ score, outcome }) => documentDetail(score, outcome)) };
}

const pct = (value: number | null) => (value === null ? "–" : `${(value * 100).toFixed(1)}%`);
const usd = (value: number | null) => (value === null ? "–" : `$${value.toFixed(4)}`);
const sec = (value: number | null) => (value === null ? "–" : `${value.toFixed(1)} s`);

/** The headline rows, as [label, value] for one report. */
function headline(m: Metrics): [string, string][] {
  return [
    ["Header fields correct", `${pct(m.headerFieldAccuracy)}`],
    ["Line-item F1", `${pct(m.lineItems.f1)} (P ${pct(m.lineItems.precision)}, R ${pct(m.lineItems.recall)})`],
    ["Documents fully correct", `${pct(m.fullyCorrect.rate)} (${m.fullyCorrect.count}/${m.documents})`],
    ["Review rate", `${pct(m.reviewRate)} (${m.routes.needsReview + m.routes.failed}/${m.documents})`],
    ["Escaped errors: fields", `${m.escapedErrors.fields}`],
    ["Escaped errors: documents", `${m.escapedErrors.documents}`],
    ["Cost per document (median / p95)", `${usd(m.costUsd.median)} / ${usd(m.costUsd.p95)}`],
    ["Time per document (median / p95)", `${sec(m.seconds.median)} / ${sec(m.seconds.p95)}`],
  ];
}

export function reportMarkdown(report: Report, previous?: Report): string {
  const m = report.metrics;
  const out: string[] = [];
  out.push(`# ${report.run}`);
  out.push("");
  out.push(
    `Prompt **${report.promptVersion}** · model \`${report.model}\` (effort ${report.effort}) · **${report.split}** split, ${m.documents} invoices${report.complete ? "" : " (stopped early at the spend cap)"}` +
      (report.mode === "replay" ? ` · replay of ${report.replayOf}'s saved answers` : ""),
  );
  out.push("");
  out.push("Generated by `npm run eval`. The full record, with every wrong value, is in the JSON file of the same name; the model's raw answers are in `responses/`.");
  out.push("");

  const rows = headline(m);
  if (previous) {
    const before = headline(previous.metrics);
    out.push(`| Metric | Before: ${previous.run} | After: ${report.run} |`, "|---|---|---|");
    rows.forEach(([label, value], i) => out.push(`| ${label} | ${before[i][1]} | ${value} |`));
  } else {
    out.push("| Metric | Result |", "|---|---|");
    rows.forEach(([label, value]) => out.push(`| ${label} | ${value} |`));
  }
  out.push("");
  out.push("**Escaped errors** are wrong values that were marked high confidence, so they would reach the books without a person seeing them. An escaped document was approved automatically although a value was wrong or the invoice itself doesn't add up.");
  out.push("");

  out.push("## Accuracy per field", "", "| Field | Correct |", "|---|---|");
  for (const name of FIELD_NAMES) out.push(`| ${FIELD_LABELS[name]} | ${pct(m.fieldAccuracy[name])} |`);
  out.push("");

  out.push("## Routing", "", "| | Needed a person | Didn't |", "|---|---|---|");
  out.push(`| Sent to review (or failed) | ${m.routing.reviewedNeeded} | ${m.routing.reviewedUnneeded} |`);
  out.push(`| Approved automatically | **${m.routing.approvedWrong}** | ${m.routing.approvedCorrect} |`);
  out.push("");
  out.push(`${m.routes.failed} extraction${m.routes.failed === 1 ? "" : "s"} failed. Total cost of the run: ${usd(m.costUsd.total)}.`);
  out.push("");

  out.push("## By kind of invoice", "", "| Kind | Invoices | Fully correct | Sent to review | Escaped fields | Escaped documents |", "|---|---|---|---|---|---|");
  for (const [kind, k] of Object.entries(m.byKind)) out.push(`| ${kind} | ${k.documents} | ${k.fullyCorrect} | ${k.reviewed} | ${k.escapedFields} | ${k.escapedDocuments} |`);
  out.push("");

  const wrong = report.documents.filter((d) => d.wrong.length || d.error || d.escaped);
  out.push("## What was wrong", "");
  if (!wrong.length) out.push("Nothing: every value of every invoice matched its true value.");
  for (const d of wrong) {
    out.push(`**${d.id}** (${d.kind}, ${d.route.replace("_", " ")}${d.escaped ? ", **escaped**" : ""})${d.error ? `: extraction failed (${d.error})` : ""}`);
    for (const w of d.wrong) {
      if (w.field === "line_items") {
        out.push(`- Line items: ${d.lines.matched} of ${d.lines.truth} matched, ${d.lines.extra.length} extra`);
        for (const line of d.lines.missed) out.push(`  - missed: ${line.description} · ${line.quantity ?? "–"} × ${line.unit_price ?? "–"} = ${line.amount}`);
        for (const line of d.lines.extra) out.push(`  - extracted instead: ${line.description} · ${line.quantity ?? "–"} × ${line.unit_price ?? "–"} = ${line.amount}`);
      } else {
        out.push(`- ${FIELD_LABELS[w.field]}: got \`${w.got ?? "null"}\`, true \`${w.want ?? "null"}\` · ${w.high ? "**high confidence**" : `low (${w.reasons.join(", ")})`}`);
      }
    }
    if (!d.wrong.length && d.escaped) out.push("- Read correctly, but the invoice doesn't add up on purpose and it was approved automatically");
  }
  out.push("");
  return out.join("\n");
}
